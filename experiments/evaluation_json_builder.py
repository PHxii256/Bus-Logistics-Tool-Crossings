"""Build and append paper-aligned evaluation metrics for each comparison run.

This module reads a run-level output.json (generated by experiments/comparison/run_comparison.py),
derives the paper metrics, and appends them to an evaluation.json ledger.
"""

from __future__ import annotations

import argparse
import json
import math
import os
from datetime import datetime
from typing import Any, Dict, List, Tuple


_MODE_ALIASES = {
    "strictly_constrained": "strictly_constrained",
    "constrained": "strictly_constrained",
    "weakly_constrained": "weakly_constrained",
    "unconstrained": "weakly_constrained",
    "door_to_door": "door_to_door",
}


def _safe_float(v: Any, default: float | None = None) -> float | None:
    try:
        x = float(v)
        if math.isfinite(x):
            return x
        return default
    except (TypeError, ValueError):
        return default


def _safe_int(v: Any, default: int = 0) -> int:
    try:
        return int(v)
    except (TypeError, ValueError):
        return default


def _normalize_stage_for_crossing(stage_value: Any) -> str:
    token = str(stage_value or "").strip().upper()
    if "MIDDLE" in token:
        return "MIDDLE"
    if token in {"HIGH", "HIGHSCHOOL", "HIGH_SCHOOL", "SECONDARY"}:
        return "HIGH"
    if "HIGH" in token:
        return "HIGH"
    return token


def _is_crossing_allowed_student(stage_value: Any, disabled_value: Any) -> bool:
    if bool(disabled_value):
        return False
    stage = _normalize_stage_for_crossing(stage_value)
    return stage in {"MIDDLE", "HIGH"}


def _count_allowed_crossing_students(mode_data: Dict[str, Any]) -> int:
    total_allowed = 0
    for rec in (mode_data.get("students") or []):
        if not isinstance(rec, dict):
            continue
        if _is_crossing_allowed_student(
            rec.get("stage"),
            rec.get("physically_mentally_disabled"),
        ):
            total_allowed += 1
    for rec in (mode_data.get("unserved_students") or []):
        if not isinstance(rec, dict):
            continue
        if _is_crossing_allowed_student(
            rec.get("stage"),
            rec.get("physically_mentally_disabled"),
        ):
            total_allowed += 1
    return total_allowed


def _ratio_pct(numerator: Any, denominator: Any) -> float | None:
    num = _safe_float(numerator, None)
    den = _safe_float(denominator, None)
    if num is None or den is None or den <= 0:
        return None
    bounded_num = max(0.0, min(num, den))
    return float((100.0 * bounded_num) / den)


def _allowed_mean_walking_dist(mode_data: Dict[str, Any]) -> float | None:
    vals: List[float] = []
    for rec in (mode_data.get("students") or []):
        if not isinstance(rec, dict):
            continue
        walk_limit = _safe_float(rec.get("walk_limit_m"), None)
        walk_dist = _safe_float(rec.get("walk_distance_m"), None)
        if walk_limit is None or walk_dist is None:
            continue
        if walk_limit > 0:
            vals.append(walk_dist)
    if not vals:
        return None
    return float(sum(vals) / len(vals))


def _normalize_mode_key(mode_key: str) -> str:
    key = str(mode_key or "").strip().lower()
    return _MODE_ALIASES.get(key, key or "unknown")


def _ride_time_policy_label(constraints: Dict[str, Any]) -> str:
    enabled = bool(constraints.get("enabled", True))
    mrt_enabled = bool(constraints.get("mrt_enabled", constraints.get("mrt enabled", False)))
    mrt_minutes = _safe_float(constraints.get("mrt"), None)

    if not enabled:
        return "no_mrt"
    if mrt_enabled and mrt_minutes is not None and mrt_minutes > 0:
        return "fixed_mrt"

    bidirectional = bool(constraints.get("bidirectional_check", True))
    return "dmrt_bidirectional_lenient" if bidirectional else "dmrt_strict_am"


def _fleet_utilization(mode_data: Dict[str, Any]) -> float | None:
    routes = mode_data.get("routes") or []
    if not routes:
        return 0.0

    cap = _safe_float(mode_data.get("bus_capacity"), None)
    if cap is None or cap <= 0:
        return None

    vals = []
    for r in routes:
        load = _safe_float((r or {}).get("students_count"), None)
        if load is None:
            continue
        vals.append(load / cap)

    if not vals:
        return None
    return float(sum(vals) / len(vals))


def _ride_ratio_stats(mode_data: Dict[str, Any]) -> Tuple[List[float], int]:
    ratios: List[float] = []
    missing = 0
    for s in (mode_data.get("students") or []):
        ride = _safe_float((s or {}).get("ride_time_min"), None)
        direct = _safe_float((s or {}).get("direct_potential_min"), None)
        if ride is None or direct is None or direct <= 0:
            missing += 1
            continue
        ratios.append(ride / direct)
    return ratios, missing


def _welfare_violation_rate(mode_data: Dict[str, Any], constraints: Dict[str, Any]) -> Tuple[float | None, int]:
    floor_min = _safe_float(constraints.get("floor_minutes"), 45.0)
    tau_add = _safe_float(
        constraints.get("acceptable_offset_minutes", constraints.get("ceiling_minutes")),
        30.0,
    )

    mrt_enabled = bool(constraints.get("mrt_enabled", constraints.get("mrt enabled", False)))
    mrt_minutes = _safe_float(constraints.get("mrt"), None)

    checked = 0
    violations = 0

    for s in (mode_data.get("students") or []):
        ride = _safe_float((s or {}).get("ride_time_min"), None)
        direct = _safe_float((s or {}).get("direct_potential_min"), None)
        if ride is None or direct is None or direct <= 0:
            continue

        checked += 1
        if mrt_enabled and mrt_minutes is not None and mrt_minutes > 0:
            cap = mrt_minutes
        else:
            cap = max(float(floor_min), float(direct) + float(tau_add))

        if ride > cap:
            violations += 1

    if checked == 0:
        return None, 0
    return float(violations / checked), checked


def _derive_paper_metrics(mode_data: Dict[str, Any], constraints: Dict[str, Any]) -> Dict[str, Any]:
    served = _safe_int(mode_data.get("students_served"), 0)
    unserved = _safe_int(mode_data.get("students_unserved"), 0)
    total = max(0, served + unserved)

    service_rate = (served / total) if total > 0 else 0.0
    active_routes = _safe_int(mode_data.get("routes_created"), 0)
    total_route_time = _safe_float(mode_data.get("total_route_time_min"), 0.0)
    avg_route_time = _safe_float(mode_data.get("avg_route_time_min"), 0.0)

    walk_stats = mode_data.get("walk_stats") or {}
    mean_walk = _safe_float(walk_stats.get("avg_walk_dist_m"), None)
    vals = [
        _safe_float((s or {}).get("walk_distance_m"), None)
        for s in (mode_data.get("students") or [])
    ]
    vals = [x for x in vals if x is not None]
    if mean_walk is None:
        mean_walk = float(sum(vals) / len(vals)) if vals else 0.0
    elif mean_walk <= 0.0 and any(x > 0.0 for x in vals):
        # Guard against stale/zero walk_stats when student payload has valid walks.
        mean_walk = float(sum(vals) / len(vals))

    allowed_mean_walk = _safe_float(mode_data.get("allowed_mean_walk_dist_m"), None)
    if allowed_mean_walk is None:
        allowed_mean_walk = _allowed_mean_walking_dist(mode_data)

    fleet_util = _safe_float(mode_data.get("fleet_utilization_ratio"), None)
    if fleet_util is None:
        fleet_util = _fleet_utilization(mode_data)

    ratios, missing_ratio_fields = _ride_ratio_stats(mode_data)
    if ratios:
        rr_mean = float(sum(ratios) / len(ratios))
        rr_max = float(max(ratios))
        rr_std = float((sum((x - rr_mean) ** 2 for x in ratios) / len(ratios)) ** 0.5)
    else:
        rr_mean = None
        rr_std = None
        rr_max = None

    wvr, n_wvr_checked = _welfare_violation_rate(mode_data, constraints)

    allowed_crossing_students = _safe_int(mode_data.get("allowed_crossing_students"), 0)
    if allowed_crossing_students <= 0:
        allowed_crossing_students = _count_allowed_crossing_students(mode_data)

    students_used_allowed = mode_data.get("students_using_synthetic_crossings_allowed")
    if students_used_allowed is None:
        students_used_allowed = sum(
            1
            for rec in (mode_data.get("students") or [])
            if isinstance(rec, dict)
            and bool(rec.get("used_synthetic_crossing"))
            and _is_crossing_allowed_student(
                rec.get("stage"),
                rec.get("physically_mentally_disabled"),
            )
        )
    students_used_allowed = _safe_int(students_used_allowed, 0)

    crossing_bfs_stats = mode_data.get("crossing_bfs_stats") or {}
    students_considered_allowed = mode_data.get("students_considered_synthetic_crossings_allowed")
    if students_considered_allowed is None:
        students_considered_allowed = (crossing_bfs_stats or {}).get("allowed_students_explored_crossing", 0)
    students_considered_allowed = _safe_int(students_considered_allowed, 0)
    students_considered_allowed = max(students_considered_allowed, students_used_allowed)

    return {
        "ServiceRate": service_rate,
        "ActiveRoutes": active_routes,
        "TotalRouteTime": total_route_time,
        "AvgRouteTime": avg_route_time,
        "FleetUtilization": fleet_util,
        "RideRatioMean": rr_mean,
        "RideRatioStd": rr_std,
        "WelfareViolationRate": wvr,
        "RideRatioMax": rr_max,
        "MeanWalkDist": mean_walk,
        "AllowedMeanWalkingDist": allowed_mean_walk,
        "CrossingTierShare": mode_data.get("crossing_tier_share_by_stage", {}),
        "SyntheticCrossingsUsed": _safe_int(mode_data.get("synthetic_crossings_used"), 0),
        "UsedCrossing": _ratio_pct(students_used_allowed, allowed_crossing_students),
        "ConsideredCrossing": _ratio_pct(students_considered_allowed, allowed_crossing_students),
        "_n_ratio_samples": len(ratios),
        "_n_missing_ratio_fields": missing_ratio_fields,
        "_n_welfare_checked": n_wvr_checked,
    }


def _derive_mode_performance_metrics(mode_data: Dict[str, Any]) -> Dict[str, Any]:
    """Extract mode-level ALNS performance metrics for evaluation reporting."""
    op_perf = mode_data.get("operator_performance") or {}
    alns_diag = mode_data.get("alns_diagnostics") or {}

    runtime_seconds = _safe_float(mode_data.get("mode_wall_time_seconds"), None)
    if runtime_seconds is None:
        runtime_seconds = _safe_float(mode_data.get("alns_runtime_seconds"), None)

    executed_iterations = _safe_int(
        op_perf.get("executed_iterations"),
        _safe_int(mode_data.get("executed_iterations"), 0),
    )
    stop_reason = str(alns_diag.get("stop_reason") or "unknown")

    return {
        "RuntimeSeconds": runtime_seconds,
        "ExecutedIterations": executed_iterations,
        "StopReason": stop_reason,
    }


def _build_stop_reason_distribution(modes_out: Dict[str, Any]) -> Dict[str, Any]:
    """Build stop-reason counts and shares across modes in one run."""
    counts: Dict[str, int] = {}
    total = 0

    for mode_entry in (modes_out or {}).values():
        reason = str(
            ((mode_entry or {}).get("performance_metrics") or {}).get("StopReason")
            or "unknown"
        )
        counts[reason] = counts.get(reason, 0) + 1
        total += 1

    if total <= 0:
        return {"counts": {}, "share": {}, "total_modes": 0}

    share = {k: round(v / total, 6) for k, v in counts.items()}
    return {"counts": counts, "share": share, "total_modes": total}


def _build_instance_size_performance_summary(runs: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Aggregate runtime, iterations, and stop reasons by instance size."""
    grouped: Dict[str, Dict[str, Any]] = {}

    for run in runs or []:
        run_cfg = (run or {}).get("config") or {}
        n_students = run_cfg.get("n_students")
        if n_students is None:
            continue

        size_key = str(n_students)
        g = grouped.setdefault(size_key, {"runs": 0, "modes": {}})
        g["runs"] += 1

        for mode_key, mode_entry in ((run or {}).get("modes") or {}).items():
            perf = (mode_entry or {}).get("performance_metrics") or {}
            mg = g["modes"].setdefault(
                mode_key,
                {
                    "runtime_seconds": [],
                    "executed_iterations": [],
                    "stop_reason_counts": {},
                },
            )

            runtime_s = _safe_float(perf.get("RuntimeSeconds"), None)
            if runtime_s is not None:
                mg["runtime_seconds"].append(runtime_s)

            iters = _safe_int(perf.get("ExecutedIterations"), 0)
            if iters > 0:
                mg["executed_iterations"].append(float(iters))

            reason = str(perf.get("StopReason") or "unknown")
            mg["stop_reason_counts"][reason] = mg["stop_reason_counts"].get(reason, 0) + 1

    out: Dict[str, Any] = {}
    for size_key, g in grouped.items():
        out_modes: Dict[str, Any] = {}
        for mode_key, mg in g["modes"].items():
            runtimes = mg["runtime_seconds"]
            iterations = mg["executed_iterations"]

            runtime_stats = None
            if runtimes:
                runtime_stats = {
                    "n": len(runtimes),
                    "mean": round(sum(runtimes) / len(runtimes), 6),
                    "min": round(min(runtimes), 6),
                    "max": round(max(runtimes), 6),
                }

            iter_stats = None
            if iterations:
                iter_stats = {
                    "n": len(iterations),
                    "mean": round(sum(iterations) / len(iterations), 6),
                    "min": int(min(iterations)),
                    "max": int(max(iterations)),
                }

            out_modes[mode_key] = {
                "runtime_seconds": runtime_stats,
                "executed_iterations": iter_stats,
                "stop_reason_counts": mg["stop_reason_counts"],
            }

        out[size_key] = {
            "runs": g["runs"],
            "modes": out_modes,
        }

    return out


def build_evaluation_entry(payload: Dict[str, Any], source_output_path: str) -> Dict[str, Any]:
    config = payload.get("config") or {}
    constraints = config.get("constraints") or {}

    modes_out: Dict[str, Any] = {}
    for raw_mode_key, mode_data in (payload.get("modes") or {}).items():
        if not isinstance(mode_data, dict):
            continue

        normalized = _normalize_mode_key(raw_mode_key)
        paper_metrics = _derive_paper_metrics(mode_data, constraints)
        perf_metrics = _derive_mode_performance_metrics(mode_data)

        alns_diag = mode_data.get("alns_diagnostics") or {}
        students = mode_data.get("students") or []

        modes_out[normalized] = {
            "source_mode_key": raw_mode_key,
            "ride_time_policy": _ride_time_policy_label(constraints),
            "counts": {
                "students_total": _safe_int(mode_data.get("students_served"), 0)
                + _safe_int(mode_data.get("students_unserved"), 0),
                "students_served": _safe_int(mode_data.get("students_served"), 0),
                "students_unserved": _safe_int(mode_data.get("students_unserved"), 0),
                "active_routes": _safe_int(mode_data.get("routes_created"), 0),
            },
            "paper_metrics": {
                k: v for k, v in paper_metrics.items() if not k.startswith("_")
            },
            "performance_metrics": perf_metrics,
            "diagnostics": {
                "stop_reason": perf_metrics.get("StopReason"),
                "executed_iterations": _safe_int(perf_metrics.get("ExecutedIterations"), 0),
                "merge_tail_ran": (alns_diag.get("merge_tail") or {}).get("ran"),
                "theoretical_optimum_polish": alns_diag.get("stop_reason") == "theoretical_optimum_polish",
            },
            "quality_flags": {
                "n_students_with_valid_ride_ratio": paper_metrics.get("_n_ratio_samples", 0),
                "n_students_missing_direct_or_ride": paper_metrics.get("_n_missing_ratio_fields", 0),
                "n_students_checked_for_welfare": paper_metrics.get("_n_welfare_checked", 0),
                "students_payload_size": len(students),
            },
        }

    runtime_seconds_by_mode = {
        mode_key: ((mode_entry or {}).get("performance_metrics") or {}).get("RuntimeSeconds")
        for mode_key, mode_entry in modes_out.items()
    }
    executed_iterations_by_mode = {
        mode_key: _safe_int(
            ((mode_entry or {}).get("performance_metrics") or {}).get("ExecutedIterations"),
            0,
        )
        for mode_key, mode_entry in modes_out.items()
    }

    run_id = os.path.basename(os.path.dirname(os.path.abspath(source_output_path)))
    return {
        "run_id": run_id,
        "source_output": os.path.abspath(source_output_path),
        "generated_at": payload.get("generated_at"),
        "recorded_at": datetime.utcnow().replace(microsecond=0).isoformat() + "Z",
        "config": {
            "n_students": config.get("n_students"),
            "seed": config.get("seed"),
            "iterations": config.get("iterations"),
            "buses_count": config.get("buses_count"),
            "buses_capacity": config.get("buses_capacity"),
            "constraints": constraints,
        },
        "performance": {
            "instance_size_students": config.get("n_students"),
            "runtime_seconds_by_mode": runtime_seconds_by_mode,
            "executed_iterations_by_mode": executed_iterations_by_mode,
            "stop_reason_distribution": _build_stop_reason_distribution(modes_out),
        },
        "modes": modes_out,
    }


def append_to_evaluation_file(entry: Dict[str, Any], evaluation_json_path: str) -> Dict[str, Any]:
    if os.path.exists(evaluation_json_path):
        with open(evaluation_json_path, "r", encoding="utf-8") as f:
            store = json.load(f)
    else:
        store = {"schema_version": "1.0", "runs": []}

    if not isinstance(store, dict):
        store = {"schema_version": "1.0", "runs": []}
    store.setdefault("schema_version", "1.0")
    store.setdefault("runs", [])

    runs = store.get("runs") or []

    replacement_idx = None
    for idx, old in enumerate(runs):
        same_source = (old or {}).get("source_output") == entry.get("source_output")
        same_generated_at = (old or {}).get("generated_at") == entry.get("generated_at")
        if same_source and same_generated_at:
            replacement_idx = idx
            break

    if replacement_idx is None:
        runs.append(entry)
    else:
        runs[replacement_idx] = entry

    store["runs"] = runs
    store["performance_summary_by_instance_size"] = _build_instance_size_performance_summary(runs)
    store["updated_at"] = datetime.utcnow().replace(microsecond=0).isoformat() + "Z"

    folder = os.path.dirname(evaluation_json_path)
    if folder:
        os.makedirs(folder, exist_ok=True)
    with open(evaluation_json_path, "w", encoding="utf-8") as f:
        json.dump(store, f, indent=2, ensure_ascii=True)

    return {
        "evaluation_json": os.path.abspath(evaluation_json_path),
        "runs_total": len(runs),
        "run_id": entry.get("run_id"),
        "modes_recorded": sorted((entry.get("modes") or {}).keys()),
    }


def append_from_output(output_json_path: str, evaluation_json_path: str | None = None) -> Dict[str, Any]:
    with open(output_json_path, "r", encoding="utf-8") as f:
        payload = json.load(f)

    if evaluation_json_path is None:
        evaluation_json_path = os.path.join(
            os.path.dirname(os.path.abspath(output_json_path)),
            "evaluation.json",
        )

    entry = build_evaluation_entry(payload, output_json_path)
    return append_to_evaluation_file(entry, evaluation_json_path)


def main() -> None:
    parser = argparse.ArgumentParser(description="Append paper metrics to evaluation.json")
    parser.add_argument("output", help="Path to run output.json")
    parser.add_argument("--evaluation", default=None, help="Target evaluation.json path")
    args = parser.parse_args()

    summary = append_from_output(args.output, args.evaluation)
    print(json.dumps(summary, indent=2, ensure_ascii=True))


if __name__ == "__main__":
    main()
